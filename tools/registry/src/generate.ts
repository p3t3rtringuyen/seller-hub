// Turns a Discovery into the gitignored *.generated.* files and validates the conventions.
// Deterministic: same files in, same bytes out (no timestamps).

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, posix, relative } from "node:path";
import { pathToFileURL } from "node:url";
import { KEBAB, readRepoFile, type Discovery, type Found } from "./discover";

const HEADER = "// GENERATED by tools/registry (pnpm gen) — do not edit, do not commit.\n";
const ROLES = new Set(["owner", "admin", "manager", "analyst", "viewer"]);

export interface GenerateResult {
  written: string[];
  errors: string[];
  summary: Record<string, number>;
  /** Permission -> roles, as declared by *.permissions.ts files. */
  permissions: Map<string, Set<string>>;
  commandKinds: string[];
}

function write(root: string, file: string, content: string, written: string[]): void {
  const abs = join(root, file);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, content);
  written.push(file);
}

/** Import specifier (no extension) of `target` as seen from the generated file `from`. */
function spec(from: string, target: string): string {
  let rel = posix.relative(posix.dirname(from), target.replace(/\.tsx?$/, ""));
  if (!rel.startsWith(".")) rel = `./${rel}`;
  return rel;
}

async function load(root: string, file: string): Promise<unknown> {
  const mod = (await import(pathToFileURL(join(root, file)).href)) as { default?: unknown };
  if (mod.default === undefined) throw new Error(`${file}: missing default export`);
  return mod.default;
}

const asArray = <T>(v: T | readonly T[]): T[] => (Array.isArray(v) ? [...(v as T[])] : [v as T]);

function hasDefaultExport(root: string, f: Found): boolean {
  return (
    /export\s+default\s/.test(readRepoFile(root, f.file)) ||
    /export\s*\{[^}]*\bas\s+default\b/.test(readRepoFile(root, f.file))
  );
}

export async function generate(d: Discovery): Promise<GenerateResult> {
  const { root } = d;
  const errors = [...d.errors];
  const written: string[] = [];
  const f = d.found;

  // --- structural checks -----------------------------------------------------------------------------
  for (const kind of [
    "routes",
    "permissions",
    "jobs",
    "syncs",
    "commands",
    "publics",
    "seeds",
    "navs",
    "slots",
    "metrics",
  ] as const) {
    for (const item of f[kind]) {
      if (!KEBAB.test(item.key)) errors.push(`${item.file}: key "${item.key}" must be kebab-case`);
      if (
        kind !== "navs" &&
        kind !== "slots" &&
        kind !== "metrics" &&
        !d.modules.includes(item.module)
      ) {
        errors.push(
          `${item.file}: modules/${item.module} has no package.json (create it with pnpm new:module ${item.module})`,
        );
      }
      if (kind !== "publics" && !hasDefaultExport(root, item))
        errors.push(`${item.file}: must default-export its definition`);
    }
  }
  for (const item of [...f.routes, ...f.jobs, ...f.syncs, ...f.commands]) {
    // These dirs hold *.route.ts etc. directly under <key>/ — nested folders are fine for helpers.
    void item;
  }

  // --- permissions (import: plain data) ---------------------------------------------------------------
  const permissions = new Map<string, Set<string>>();
  const permissionList: { module: string; key: string; file: string }[] = [];
  for (const p of f.permissions) {
    try {
      const decls = asArray(await load(root, p.file)) as {
        permission?: unknown;
        roles?: unknown;
      }[];
      for (const decl of decls) {
        const name = decl.permission;
        const roles = decl.roles;
        if (typeof name !== "string" || !/^[a-z]+(\.[a-z][a-z0-9-]*)+$/.test(name)) {
          errors.push(`${p.file}: permission "${String(name)}" must look like <area>.<action>`);
          continue;
        }
        if (
          !Array.isArray(roles) ||
          roles.length === 0 ||
          roles.some((r) => !ROLES.has(String(r)))
        ) {
          errors.push(`${p.file}: ${name} needs roles from ${[...ROLES].join(", ")}`);
          continue;
        }
        const set = permissions.get(name);
        const incoming = new Set(roles.map(String));
        if (set && (set.size !== incoming.size || [...incoming].some((r) => !set.has(r)))) {
          errors.push(`${p.file}: permission ${name} is declared with different roles elsewhere`);
        }
        permissions.set(name, incoming);
      }
      permissionList.push(p);
    } catch (e) {
      errors.push(`${p.file}: ${(e as Error).message}`);
    }
  }

  // --- sync definitions / jobs / commands (import: validates keys) ------------------------------------
  const syncKeys = new Map<string, string>();
  for (const s of f.syncs) {
    try {
      for (const def of asArray(await load(root, s.file)) as {
        key?: unknown;
        family?: unknown;
      }[]) {
        const key = String(def.key);
        if (typeof def.key !== "string" || !key.startsWith(`${s.module}.`))
          errors.push(`${s.file}: sync key "${key}" must start with "${s.module}."`);
        if (typeof def.family !== "string") errors.push(`${s.file}: sync ${key} needs a family`);
        if (syncKeys.has(key))
          errors.push(`${s.file}: duplicate sync key ${key} (also in ${syncKeys.get(key)})`);
        syncKeys.set(key, s.file);
      }
    } catch (e) {
      errors.push(`${s.file}: ${(e as Error).message}`);
    }
  }
  const queues = new Map<string, string>();
  for (const j of f.jobs) {
    try {
      for (const def of asArray(await load(root, j.file)) as {
        queue?: unknown;
        process?: unknown;
      }[]) {
        const queue = String(def.queue);
        if (typeof def.queue !== "string" || !queue.startsWith(`${j.module}.`))
          errors.push(
            `${j.file}: queue "${queue}" must be <module>.<job> starting with "${j.module}."`,
          );
        if (typeof def.process !== "function")
          errors.push(`${j.file}: job ${queue} needs process()`);
        if (queues.has(queue))
          errors.push(`${j.file}: duplicate queue ${queue} (also in ${queues.get(queue)})`);
        queues.set(queue, j.file);
      }
    } catch (e) {
      errors.push(`${j.file}: ${(e as Error).message}`);
    }
  }
  const kinds = new Map<string, string>();
  for (const c of f.commands) {
    try {
      for (const def of asArray(await load(root, c.file)) as {
        kind?: unknown;
        permission?: unknown;
        batchMax?: unknown;
        payloadSchema?: unknown;
        apply?: unknown;
      }[]) {
        const kind = String(def.kind);
        if (typeof def.kind !== "string" || !/^[a-z]+(\.[a-z][a-z0-9-]*)+$/.test(kind))
          errors.push(`${c.file}: command kind "${kind}" must look like ads.target.update-bid`);
        if (kinds.has(kind))
          errors.push(`${c.file}: duplicate command kind ${kind} (also in ${kinds.get(kind)})`);
        kinds.set(kind, c.file);
        if (typeof def.permission !== "string" || !permissions.has(def.permission))
          errors.push(
            `${c.file}: ${kind} uses permission "${String(def.permission)}" that no *.permissions.ts declares`,
          );
        if (typeof def.batchMax !== "number" || def.batchMax < 1)
          errors.push(`${c.file}: ${kind} needs batchMax >= 1`);
        if (typeof def.payloadSchema !== "object" || def.payloadSchema === null)
          errors.push(`${c.file}: ${kind} needs a payloadSchema (JSON Schema)`);
        if (typeof def.apply !== "function") errors.push(`${c.file}: ${kind} needs apply()`);
      }
    } catch (e) {
      errors.push(`${c.file}: ${(e as Error).message}`);
    }
  }

  // --- web: nav / slots / messages / metrics -----------------------------------------------------------
  const navIds = new Set<string>();
  for (const n of f.navs) {
    try {
      for (const e of asArray(await load(root, n.file)) as Record<string, unknown>[]) {
        for (const field of ["id", "labelKey", "href", "section", "permission"] as const) {
          if (typeof e[field] !== "string")
            errors.push(`${n.file}: nav entry needs string "${field}"`);
        }
        if (typeof e.order !== "number") errors.push(`${n.file}: nav entry needs numeric "order"`);
        if (typeof e.permission === "string" && !permissions.has(e.permission))
          errors.push(
            `${n.file}: nav permission "${e.permission}" is not declared by any *.permissions.ts`,
          );
        if (navIds.has(String(e.id))) errors.push(`${n.file}: duplicate nav id ${String(e.id)}`);
        navIds.add(String(e.id));
      }
    } catch (e) {
      errors.push(`${n.file}: ${(e as Error).message}`);
    }
  }
  for (const s of f.slots) {
    const text = readRepoFile(root, s.file);
    if (
      !/\bslot\s*:\s*["'][a-z0-9.-]+["']/.test(text) ||
      !/\bcomponent\b/.test(text) ||
      !/\border\s*:\s*\d+/.test(text)
    ) {
      errors.push(
        `${s.file}: a slot file default-exports { slot: "<name>", component, order: <n> }`,
      );
    }
  }
  for (const m of f.metrics) {
    try {
      for (const def of asArray(await load(root, m.file)) as { id?: unknown }[]) {
        if (typeof def.id !== "string") errors.push(`${m.file}: metric needs an id`);
      }
    } catch (e) {
      errors.push(`${m.file}: ${(e as Error).message}`);
    }
  }
  for (const msg of d.messages) {
    try {
      JSON.parse(readRepoFile(root, msg.file));
    } catch {
      errors.push(`${msg.file}: invalid JSON`);
    }
  }

  // --- migrations ---------------------------------------------------------------------------------------
  const seen = new Map<string, string>();
  for (const m of d.migrations) {
    if (seen.has(m.timestamp))
      errors.push(`${m.file}: timestamp ${m.timestamp} is also used by ${seen.get(m.timestamp)}`);
    seen.set(m.timestamp, m.file);
  }

  if (errors.length)
    return { written, errors, summary: {}, permissions, commandKinds: [...kinds.keys()] };

  // --- emit ----------------------------------------------------------------------------------------------
  const importLines = (from: string, items: Found[], prefix: string): string =>
    items.map((it, i) => `import ${prefix}${i} from "${spec(from, it.file)}";`).join("\n");
  const entries = (items: Found[], prefix: string): string =>
    items
      .map(
        (it, i) =>
          `  { module: "${it.module}", key: "${it.key}", file: "${it.file}", value: ${prefix}${i} },`,
      )
      .join("\n");
  const asArrayFn =
    "const asArray = <T,>(v: T | readonly T[]): T[] => (Array.isArray(v) ? [...(v as T[])] : [v as T]);\n";

  // API registry
  const apiFile = "apps/api/src/registry.generated.ts";
  write(
    root,
    apiFile,
    `${HEADER}/* eslint-disable */
import type { CommandHandler, PermissionDecl, RouteModule } from "@seller-hub/core";
${importLines(apiFile, f.routes, "route")}
${importLines(apiFile, f.permissions, "perm")}
${importLines(apiFile, f.commands, "cmd")}

${asArrayFn}
export interface Registered<T> { module: string; key: string; file: string; value: T }
const wrap = <T,>(items: { module: string; key: string; file: string; value: T | readonly T[] }[]): Registered<T>[] =>
  items.flatMap((i) => asArray(i.value).map((value) => ({ module: i.module, key: i.key, file: i.file, value })));

export const routes: Registered<RouteModule>[] = wrap<RouteModule>([
${entries(f.routes, "route")}
]);
export const permissions: Registered<PermissionDecl>[] = wrap<PermissionDecl>([
${entries(f.permissions, "perm")}
]);
export const commands: Registered<CommandHandler<any>>[] = wrap<CommandHandler<any>>([
${entries(f.commands, "cmd")}
]);
`,
    written,
  );

  // Worker registry
  const workerFile = "apps/worker/src/registry.generated.ts";
  write(
    root,
    workerFile,
    `${HEADER}/* eslint-disable */
import type { CommandHandler, JobDefinition, SyncDefinition } from "@seller-hub/core";
${importLines(workerFile, f.syncs, "sync")}
${importLines(workerFile, f.jobs, "job")}
${importLines(workerFile, f.commands, "cmd")}

${asArrayFn}
export interface Registered<T> { module: string; key: string; file: string; value: T }
const wrap = <T,>(items: { module: string; key: string; file: string; value: T | readonly T[] }[]): Registered<T>[] =>
  items.flatMap((i) => asArray(i.value).map((value) => ({ module: i.module, key: i.key, file: i.file, value })));

export const syncs: Registered<SyncDefinition>[] = wrap<SyncDefinition>([
${entries(f.syncs, "sync")}
]);
export const jobs: Registered<JobDefinition<any>>[] = wrap<JobDefinition<any>>([
${entries(f.jobs, "job")}
]);
export const commands: Registered<CommandHandler<any>>[] = wrap<CommandHandler<any>>([
${entries(f.commands, "cmd")}
]);
`,
    written,
  );

  // Module public entries
  for (const m of d.modules) {
    const own = f.publics.filter((p) => p.module === m);
    const file = `modules/${m}/src/public.generated.ts`;
    write(
      root,
      file,
      `${HEADER}${own.length ? own.map((p) => `export * from "./public/${p.key}";`).join("\n") : "export {};"}\n`,
      written,
    );
  }

  // Web
  const navFile = "apps/web/nav.generated.ts";
  write(
    root,
    navFile,
    `${HEADER}/* eslint-disable */
${importLines(navFile, f.navs, "nav")}

${asArrayFn}
export interface NavEntry { id: string; labelKey: string; href: string; section: string; order: number; permission: string }
export const navEntries: NavEntry[] = [
${f.navs.map((_, i) => `  ...asArray<NavEntry>(nav${i})`).join(",\n")}
].sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
`,
    written,
  );

  const slotFile = "apps/web/slots.generated.ts";
  write(
    root,
    slotFile,
    `${HEADER}/* eslint-disable */
${importLines(slotFile, f.slots, "slot")}

export interface SlotRegistration { slot: string; component: unknown; order: number }
export const slotRegistrations: SlotRegistration[] = ([
${f.slots.map((_, i) => `  slot${i}`).join(",\n")}
] as SlotRegistration[]).sort((a, b) => a.slot.localeCompare(b.slot) || a.order - b.order);
export const slotsFor = (name: string): SlotRegistration[] => slotRegistrations.filter((s) => s.slot === name);
`,
    written,
  );

  const locales = [...new Set(d.messages.map((m) => m.locale))].sort();
  const msgFile = "apps/web/messages.generated.ts";
  write(
    root,
    msgFile,
    `${HEADER}/* eslint-disable */
${d.messages.map((m, i) => `import msg${i} from "${spec(msgFile, m.file)}";`).join("\n")}

/** locale -> namespace "<module>.<key>" -> messages */
export const messagesByLocale: Record<string, Record<string, Record<string, unknown>>> = {
${locales
  .map(
    (loc) =>
      `  "${loc}": {\n${d.messages
        .map((m, i) => ({ m, i }))
        .filter(({ m }) => m.locale === loc)
        .map(({ m, i }) => `    "${m.module}.${m.key}": msg${i} as Record<string, unknown>,`)
        .join("\n")}\n  },`,
  )
  .join("\n")}
};
`,
    written,
  );

  const metricFile = "packages/metrics/src/index.generated.ts";
  write(
    root,
    metricFile,
    `${HEADER}/* eslint-disable */
import type { MetricDefinition } from "@seller-hub/core";
${importLines(metricFile, f.metrics, "metric")}

${asArrayFn}
export const metrics: MetricDefinition[] = [
${f.metrics.map((_, i) => `  ...asArray<MetricDefinition>(metric${i})`).join(",\n")}
];
`,
    written,
  );

  // Migrations / seeds index (read by packages/db)
  write(
    root,
    "db/migrations/index.generated.json",
    `${JSON.stringify({ migrations: d.migrations.map((m) => ({ file: m.file, timestamp: m.timestamp, module: m.module, key: m.key })) }, null, 2)}\n`,
    written,
  );
  write(
    root,
    "db/migrations/seeds.generated.json",
    `${JSON.stringify({ seeds: f.seeds.map((s) => ({ file: s.file, module: s.module, key: s.key })) }, null, 2)}\n`,
    written,
  );

  const summary = {
    routes: f.routes.length,
    permissions: permissions.size,
    jobs: queues.size,
    syncs: syncKeys.size,
    commands: kinds.size,
    migrations: d.migrations.length,
    seeds: f.seeds.length,
    navs: navIds.size,
    slots: f.slots.length,
    messages: d.messages.length,
    metrics: f.metrics.length,
    contracts: d.contracts.length,
  };
  void relative;
  return { written, errors, summary, permissions, commandKinds: [...kinds.keys()] };
}
