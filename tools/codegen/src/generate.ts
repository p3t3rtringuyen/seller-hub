import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { pruneSpec } from "./prune";
import type { Tooling } from "./tooling";

// Regenerates packages/amazon-{sp,ads}/src/generated from the pinned models (ADR-0006):
//   SP-API  : Swagger 2.0 (refs/amazon/selling-partner-api-models) → swagger2openapi → prune → openapi-typescript
//   Ads     : OpenAPI 3 (refs/amazon-ads/specs)                                      → prune → openapi-typescript
// plus one `operations.ts` per package that carries the catalogue metadata (rate limits, restricted flag, batch
// maxima, 207, exception ids …) so the transport never guesses.

type Obj = Record<string, unknown>;

export interface GeneratedFile {
  /** Repo-relative path with forward slashes. */
  path: string;
  content: string;
}

const HEADER = `// GENERATED by tools/codegen (ADR-0006) — do not edit by hand.
// Regenerate: pnpm --filter @seller-hub/amazon-core run codegen
`;

export function findRefsDir(repoRoot: string): string {
  const local = join(repoRoot, "refs");
  if (existsSync(local)) return local;
  // A worktree has no refs/ of its own: they live next to the main checkout's .git (CLAUDE.md).
  const common = execFileSync("git", ["rev-parse", "--path-format=absolute", "--git-common-dir"], {
    cwd: repoRoot,
    encoding: "utf8",
  }).trim();
  const shared = resolve(common, "..", "refs");
  if (!existsSync(shared)) throw new Error(`refs/ not found at ${local} or ${shared}`);
  return shared;
}

const readJson = (path: string): Obj => JSON.parse(readFileSync(path, "utf8")) as Obj;

async function pretty(source: string): Promise<string> {
  return format(source, {
    parser: "typescript",
    singleQuote: false,
    semi: true,
    printWidth: 100,
    trailingComma: "all",
  });
}

const safeName = (s: string): string => s.replace(/[^A-Za-z0-9]+/g, "_").replace(/^(\d)/, "_$1");
const q = (s: string): string => JSON.stringify(s);

function stripUndefined<T extends Obj>(o: T): T {
  return Object.fromEntries(Object.entries(o).filter(([, v]) => v !== undefined)) as T;
}

// ---------------------------------------------------------------------------------------------- SP-API

/** Catalogue region strings are free text ("FE except where noted"); keep the leading region code. */
export function normaliseRegions(raw: unknown): string[] | undefined {
  if (!Array.isArray(raw)) return undefined;
  const set = new Set<string>();
  for (const r of raw) {
    const m = /^\s*(na|eu|fe)\b/i.exec(String(r));
    if (m) set.add((m[1] as string).toLowerCase());
  }
  return set.size ? [...set].sort() : undefined;
}

interface SpAllow {
  apis: { api: string; version: string; operations: "*" | string[] }[];
}

export async function generateSp(repoRoot: string, tooling: Tooling): Promise<GeneratedFile[]> {
  const refs = findRefsDir(repoRoot);
  const allow = readJson(
    join(repoRoot, "tools/codegen/config/sp-allowlist.json"),
  ) as unknown as SpAllow;
  const apisRaw = JSON.parse(readFileSync(join(repoRoot, "catalog/spapi/apis.json"), "utf8")) as
    Obj[] | { apis?: Obj[] };
  const apis = Array.isArray(apisRaw) ? apisRaw : (apisRaw.apis ?? []);
  const ops = Object.values(readJson(join(repoRoot, "catalog/spapi/operations.json"))) as Obj[];

  const out: GeneratedFile[] = [];
  const imports: string[] = [];
  const typeEntries: string[] = [];
  const metaEntries: string[] = [];
  const seen = new Set<string>();

  for (const entry of allow.apis) {
    const api = apis.find((a) => a.api === entry.api && a.version === entry.version);
    if (!api)
      throw new Error(
        `SP allow-list: ${entry.api}@${entry.version} is not in catalog/spapi/apis.json`,
      );
    const file = join(refs, "amazon", "selling-partner-api-models", String(api.file));
    const converted = await tooling.swaggerToOpenApi(readJson(file));
    const { spec, kept, missing } = pruneSpec(converted, entry.operations);
    if (missing.length)
      throw new Error(
        `SP allow-list: ${entry.api}@${entry.version} has no operation(s) ${missing.join(", ")}`,
      );

    const typeFile = `${entry.api}-${entry.version}`;
    const alias = safeName(typeFile);
    out.push({
      path: `packages/amazon-sp/src/generated/types/${typeFile}.ts`,
      content: await pretty(
        `${HEADER}// Source: ${api.file} (catalog stamp ${String(readJson(join(repoRoot, "catalog/spapi/stamp.json")).commit).slice(0, 8)})\n${await tooling.openApiToTypes(spec)}`,
      ),
    });
    imports.push(`import type { operations as ${alias} } from "./types/${typeFile}";`);

    for (const [operationId, where] of [...kept].sort((a, b) => a[0].localeCompare(b[0]))) {
      const cat = ops.find(
        (o) => o.api === entry.api && o.version === entry.version && o.operationId === operationId,
      );
      if (!cat)
        throw new Error(
          `SP: ${entry.api}@${entry.version}.${operationId} missing from catalog/spapi/operations.json`,
        );
      if (cat.path !== where.path || cat.method !== where.method) {
        throw new Error(
          `SP: ${entry.api}.${operationId} differs between catalogue (${String(cat.method)} ${String(cat.path)}) and model (${where.method} ${where.path})`,
        );
      }
      const id = `${entry.api}.${operationId}`;
      if (seen.has(id))
        throw new Error(
          `SP: duplicate operation id ${id} (two versions of one API in the allow-list)`,
        );
      seen.add(id);
      const rate = cat.rateLimit as { rate: number; burst: number } | null | undefined;
      const meta = stripUndefined({
        id,
        api: "sp",
        family: `${entry.api}@${entry.version}`,
        method: cat.method,
        path: cat.path,
        rateLimit: rate ? { rate: rate.rate, burst: rate.burst } : undefined,
        restricted: cat.restricted === true,
        restrictedReason: cat.restrictedReason ?? undefined,
        regions: normaliseRegions(cat.regions),
        audience: cat.audience,
        idempotent: cat.method === "GET" ? true : undefined,
      });
      typeEntries.push(`  ${q(id)}: ${alias}[${q(operationId)}];`);
      metaEntries.push(`  ${q(id)}: ${JSON.stringify(meta)},`);
    }
  }

  out.push({
    path: "packages/amazon-sp/src/generated/operations.ts",
    content: await pretty(`${HEADER}
import type { OperationMeta } from "@seller-hub/amazon-core";
${imports.join("\n")}

/** Request/response types per operation, straight from Amazon's models. */
export interface SpOperationTypes {
${typeEntries.join("\n")}
}

export type SpOperationId = keyof SpOperationTypes;

/** Catalogue metadata per operation (rate limit, restricted flag, regions …), from catalog/spapi/operations.json. */
export const SP_OPERATIONS = {
${metaEntries.join("\n")}
} as const satisfies Record<SpOperationId, OperationMeta>;
`),
  });
  return out;
}

// ---------------------------------------------------------------------------------------------- Ads

interface AdsAllowEntry {
  id: string;
  api?: string;
  exception?: string;
  readPost?: boolean;
}

export async function generateAds(repoRoot: string, tooling: Tooling): Promise<GeneratedFile[]> {
  const refs = findRefsDir(repoRoot);
  const allow = (readJson(join(repoRoot, "tools/codegen/config/ads-allowlist.json")).operations ??
    []) as AdsAllowEntry[];
  const apis = (readJson(join(repoRoot, "catalog/ads/apis.json")).apis ?? []) as Obj[];
  const ops = (readJson(join(repoRoot, "catalog/ads/operations.json")).operations ?? []) as Obj[];
  const domain = (readJson(join(repoRoot, "catalog/ads/domain-map.json")).operations ??
    []) as Obj[];

  // Resolve each allow-list entry to its catalogue operation.
  const resolved = allow.map((a) => {
    const matches = ops.filter(
      (o) => o.operationId === a.id && (a.api ? o.api === a.api : o.generation === "v1"),
    );
    if (matches.length !== 1)
      throw new Error(
        `Ads allow-list: ${a.id}${a.api ? ` (${a.api})` : ""} matches ${matches.length} catalogue operations`,
      );
    const cat = matches[0] as Obj;
    const treatment = domain.find((d) => d.operationId === cat.operationId && d.api === cat.api);
    if (cat.generation === "v1") {
      if (a.exception)
        throw new Error(`Ads allow-list: ${a.id} is v1, it must not carry an exception id`);
    } else {
      const ex = treatment?.exception;
      if (!a.exception || ex !== a.exception) {
        throw new Error(
          `Ads allow-list: v0 operation ${a.id} must be a named exception; catalogue says ${String(ex)}, allow-list says ${String(a.exception)} (D53)`,
        );
      }
    }
    return { a, cat };
  });

  const byApi = new Map<string, typeof resolved>();
  for (const r of resolved)
    byApi.set(String(r.cat.api), [...(byApi.get(String(r.cat.api)) ?? []), r]);

  const out: GeneratedFile[] = [];
  const imports: string[] = [];
  const typeEntries: string[] = [];
  const metaEntries: string[] = [];
  const exceptionEntries: string[] = [];
  const seen = new Set<string>();

  for (const [apiId, group] of [...byApi].sort((x, y) => x[0].localeCompare(y[0]))) {
    const api = apis.find((x) => x.id === apiId);
    if (!api) throw new Error(`Ads: API ${apiId} not in catalog/ads/apis.json`);
    const specFile = join(refs, "amazon-ads", String(api.file));
    let raw: Obj;
    if (String(api.file).endsWith(".yaml")) {
      const { parse } = await import("yaml");
      raw = parse(readFileSync(specFile, "utf8")) as Obj;
    } else raw = readJson(specFile);
    const { spec, kept, missing } = pruneSpec(
      raw,
      group.map((g) => String(g.cat.operationId)),
    );
    if (missing.length)
      throw new Error(`Ads: spec ${apiId} has no operation(s) ${missing.join(", ")}`);
    const alias = safeName(apiId);
    out.push({
      path: `packages/amazon-ads/src/generated/types/${apiId}.ts`,
      content: await pretty(
        `${HEADER}// Source: refs/amazon-ads/${api.file}\n${await tooling.openApiToTypes(spec)}`,
      ),
    });
    imports.push(`import type { operations as ${alias} } from "./types/${apiId}";`);

    for (const { a, cat } of group.sort((x, y) =>
      String(x.cat.operationId).localeCompare(String(y.cat.operationId)),
    )) {
      const operationId = String(cat.operationId);
      const where = kept.get(operationId);
      if (!where || where.path !== cat.path || where.method !== cat.method) {
        throw new Error(
          `Ads: ${operationId} differs between catalogue and spec (${String(cat.method)} ${String(cat.path)})`,
        );
      }
      if (seen.has(operationId)) throw new Error(`Ads: duplicate operation id ${operationId}`);
      seen.add(operationId);
      const isRead =
        cat.method === "GET" ||
        a.readPost === true ||
        /^(SP|SB|SD|ST)?(Query|List|Retrieve)/.test(operationId) ||
        /^AdsApiv1(Query|Retrieve)/.test(operationId);
      const meta = stripUndefined({
        id: operationId,
        api: "ads",
        family: String(cat.api),
        method: cat.method,
        path: cat.path,
        generation: cat.generation,
        exception: a.exception,
        multiStatus207: cat.multiStatus207 === true ? true : undefined,
        batchField: cat.batchField ?? undefined,
        batchMax: cat.batchMax ?? undefined,
        accept: cat.accept,
        contentType: (cat.contentType as string[]).length ? cat.contentType : undefined,
        headers: cat.headers,
        idempotent: isRead ? true : undefined,
      });
      typeEntries.push(`  ${q(operationId)}: ${alias}[${q(operationId)}];`);
      metaEntries.push(`  ${q(operationId)}: ${JSON.stringify(meta)},`);
      if (a.exception) exceptionEntries.push(`  ${q(operationId)}: ${q(a.exception)},`);
    }
  }

  out.push({
    path: "packages/amazon-ads/src/generated/operations.ts",
    content: await pretty(`${HEADER}
import type { OperationMeta } from "@seller-hub/amazon-core";
${imports.join("\n")}

/** Request/response types per operation, straight from Amazon's specs. */
export interface AdsOperationTypes {
${typeEntries.join("\n")}
}

export type AdsOperationId = keyof AdsOperationTypes;

/** Catalogue metadata per operation (batch maxima, 207, media types, headers …), from catalog/ads/operations.json. */
export const ADS_OPERATIONS = {
${metaEntries.join("\n")}
} as const satisfies Record<AdsOperationId, OperationMeta>;

/** Every generated v0 operation and the named exception (D53) that allows it. */
export const ADS_V0_EXCEPTIONS: Readonly<Record<string, string>> = {
${exceptionEntries.join("\n")}
};
`),
  });
  return out;
}

export function defaultRepoRoot(): string {
  return resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
}
